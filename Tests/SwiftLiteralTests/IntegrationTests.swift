    @Test func fileExportWorkflow() throws {
    struct APIResponse {
      let success: Bool
      let timestamp: Date
      let data: [String: String]
    }

    let response = APIResponse(
      success: true,
      timestamp: Date(timeIntervalSince1970: 1_609_459_200),
      data: ["userId": "12345", "token": "abc123"]
    )

    let tempDir = FileManager.default.temporaryDirectory
      .appendingPathComponent("SwiftLiteralTests")
      .appendingPathComponent(UUID().uuidString)

    let url = try Literal.write(
        response,
        named: "successResponse",
      file: "APIResponse+Fixtures",
      directory: tempDir.path,
      header: "// API Test Fixtures",
      context: "Successful API response fixture"
    )
    // Cleanup
    defer { try? FileManager.default.removeItem(at: tempDir) }

    // Verify file exists
    #expect(FileManager.default.fileExists(atPath: url.path))

    // Verify file name
    #expect(url.lastPathComponent == "APIResponse+Fixtures.swift")

    // Read and verify content
    let content = try String(contentsOf: url, encoding: .utf8)
    assertInlineSnapshot(of: content, as: .description) {
      """
      // API Test Fixtures

      import Foundation

      extension APIResponse {
          /// Successful API response fixture
          static let successResponse: APIResponse = APIResponse(
              success: true,
              timestamp: Date(timeIntervalSince1970: 1609459200.0),
              data: ["token": "abc123", "userId": "12345"]
          )
      }

      """
    }
  }

    // MARK: - Custom Renderer Test

    @Test func customRenderer() throws {
    struct CustomType {
      let value: String
    }

    // Registered on the configuration, and scoped to this test. It used to go into a
    // shared registry and stay there for whatever ran next.
    let renderers = ValueRenderers().registering(CustomType.self) { value, _ in
      "CustomType(value: \(literal: "CUSTOM_\(value.value)"))"
    }

    let custom = CustomType(value: "test")
    let code = try withDependencies {
      $0.literalConfiguration.renderers = { renderers }
    } operation: {
      try Literal.source(of: custom, named: "testCustom")
    }

    assertInlineSnapshot(of: code, as: .description) {
      """
      import Foundation

      extension CustomType { static let testCustom: CustomType = CustomType(value: "CUSTOM_test") }

      """
    }
  }

