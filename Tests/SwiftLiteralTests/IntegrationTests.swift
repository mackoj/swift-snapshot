    @Test func complexUserModel() throws {
    enum Role {
      case admin
      case manager
      case employee
    }

    struct User {
      let id: Int
      var name: String
      var role: Role
      var isActive: Bool
      var tags: [String]
    }

    let user = User(
      id: 42,
      name: "Alice",
      role: .admin,
      isActive: true,
      tags: ["admin", "beta"]
    )

    let code = try Literal.source(
        of: user,
        named: "testUserCreation",
      header: "// Test Fixtures\n// Generated by SwiftLiteral",
      context: "Test user with admin role"
    )

    assertInlineSnapshot(of: code, as: .description) {
      """
      // Test Fixtures
      // Generated by SwiftLiteral

      import Foundation

      extension User {
          /// Test user with admin role
          static let testUserCreation: User = User(
              id: 42,
              name: "Alice",
              role: .admin,
              isActive: true,
              tags: ["admin", "beta"]
          )
      }

      """
    }
  }

